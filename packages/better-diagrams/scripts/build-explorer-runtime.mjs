#!/usr/bin/env node
/**
 * Bundle the interactive HTML export's explorer (src/react/html-explorer-runtime.ts)
 * into one minified IIFE and write it, as a string, to
 * src/react/html-explorer-runtime.generated.ts — the script the exported page
 * inlines.
 *
 * Checked in rather than built on the fly so every consumer — the library
 * build, the tests, the example app reading the source — gets the page
 * without a bundler plugin. The file records the modules it was built from
 * and a hash of their text; html-explorer.test.ts recomputes the hash and
 * fails while the bundle is stale. Run after editing any of them:
 *
 *   npm run build:explorer -w @mosphere/better-diagrams
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const root = fileURLToPath(new URL("..", import.meta.url));
const entry = path.join(root, "src/react/html-explorer-runtime.ts");
const outFile = path.join(root, "src/react/html-explorer-runtime.generated.ts");

const result = await build({
  configFile: false,
  logLevel: "warn",
  build: {
    write: false,
    minify: true,
    emptyOutDir: false,
    lib: { entry, formats: ["iife"], name: "BDExplorer" },
  },
});
const chunk = (Array.isArray(result) ? result[0] : result).output.find((o) => o.type === "chunk");
if (!chunk) throw new Error("build-explorer-runtime: the bundle produced no chunk");

const inputs = Object.keys(chunk.modules)
  .map((id) => path.relative(root, id).split(path.sep).join("/"))
  .filter((rel) => !rel.startsWith(".."))
  .sort();

/** The same hash html-explorer.test.ts recomputes: path, NUL, text with LF line ends, per input. */
function hashInputs(files) {
  const hash = createHash("sha256");
  for (const rel of files) {
    hash.update(rel);
    hash.update("\0");
    hash.update(readFileSync(path.join(root, rel), "utf8").replace(/\r\n/g, "\n"));
    hash.update("\0");
  }
  return hash.digest("hex");
}

// Inlined in a <script>: a "</script" anywhere in it would end the element
// early. `<\/` means the same thing inside every string, template and regex
// literal the minifier can have left it in.
const code = chunk.code.trim().replace(/<\/script/gi, "<\\/script").replace(/<!--/g, "<\\!--");

writeFileSync(
  outFile,
  `// Generated by scripts/build-explorer-runtime.mjs — do not edit.
// \`npm run build:explorer\` rebuilds it; html-explorer.test.ts fails while it is stale.

/** The modules the bundle was built from, relative to the package root. */
export const EXPLORER_RUNTIME_INPUTS: readonly string[] = ${JSON.stringify(inputs, null, 2)};

/** sha256 over the inputs — see \`hashInputs\` in the script. */
export const EXPLORER_RUNTIME_HASH = ${JSON.stringify(hashInputs(inputs))};

/** Defines \`BDExplorer\` (\`mountExplorer\`) when run as a classic script. */
export const EXPLORER_RUNTIME = ${JSON.stringify(code)};
`,
);
console.log(`explorer runtime: ${code.length} bytes from ${inputs.length} modules → ${path.relative(root, outFile)}`);
